using namespace std;

enum typeC {
  standard, loyal, vip
};

class Customer {
  char name[50];
  char email[50];
  typeC tc;
  int osnpop;
  int doppop;
  int proizvodi;
public:
  Customer(char *name, char *email, typeC tc, int proizvodi) {
    strcpy(this->name, name);
    strcpy(this->email, email);
    this->tc = tc;
    this->proizvodi = proizvodi;
    this->osnpop = 10;
    this->doppop = 20;
  }

  friend ostream& operator<< (ostream& out, Customer& c) {
    out<<c.name<<endl;
    out<<c.email<<endl;
    out<<c.proizvodi<<endl;
    if(c.tc == standard) {
      out<<"standard"<<"0"<<endl;
    } else if (c.tc == loyal) {
      out<<"loyal"<<c.osnpop<<endl;
    } else if (c.tc == vip) {
      out<<"vip"<<c.doppop + c.osnpop<<endl;
    }
  }
};

